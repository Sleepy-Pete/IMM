$vsSource = @'
#version 460

layout (std140, row_major, binding=3) uniform LayersState
{
    mat4x4 mLayerToViewer;
    float  mLayerToViewerScale;
    float  mOpacity;
    float  mkUnused;
    float  mDrawInTime;
    vec4   mAnimParams;
    vec4   mKeepAlive[2];
    uint   mID;
} layer;

struct DisplayEye { mat4x4 mMatrix_CamPrj; };
layout (std140, row_major, binding=4) uniform DisplayState
{
    DisplayEye mEye[2];
    vec2       mResolution;
} display;

// Eye selection: multipass uploads BOTH eyes' matrices once per frame and
// switches PassState.mID per eye pass - same convention as the paint VS
// (iid = pass.mID). mEye[0] hardcoded here rendered the right eye with the
// left eye's projection.
layout (std140, binding=5) uniform PassState
{
    int mID;
    int kk1;
    int kk2;
    int kk3;
} pass;

layout(location=0) in vec3 in_position;
layout(location=1) in vec3 in_normal;
layout(location=0) out vec3 out_direction;

// 0 = normal projected depth, 1 = reverse-Z far backdrop, 2 = less/equal far backdrop.
layout(constant_id = 0) const uint hostDepthBackdropMode = 0u;

void main()
{
    vec3 viewer_position = (layer.mLayerToViewer * vec4(in_position, 1.0)).xyz;
    out_direction = normalize(in_position);
    gl_Position = display.mEye[pass.mID].mMatrix_CamPrj * vec4(viewer_position, 1.0);
    if (hostDepthBackdropMode == 1u)
    {
        gl_Position.z = 0.0;
    }
    else if (hostDepthBackdropMode == 2u)
    {
        gl_Position.z = gl_Position.w;
    }
}
'@

$fsSource = @'
#version 460

layout (std140, row_major, binding=3) uniform LayersState
{
    mat4x4 mLayerToViewer;
    float  mLayerToViewerScale;
    float  mOpacity;
    float  mkUnused;
    float  mDrawInTime;
    vec4   mAnimParams;
    vec4   mKeepAlive[2];
    uint   mID;
} layer;

layout(binding = 0) uniform sampler2D pictureTexture;
layout(location=0) in vec3 in_direction;
layout(location=0) out vec4 out_color;

// Diagnostic, off unless IMM_UNITY_VK_PIC_DEBUG is set. 1 = solid magenta at
// full alpha, bypassing the texture sample entirely. This is the one test that
// cannot be misread: if the sky turns magenta the geometry, pipeline, descriptor
// set and blend state are all sound and the fault is in sampling; if it stays
// black the fragments never survive at all and the fault is upstream of the
// shader. Every CPU-side probe reports success either way, which is exactly why
// this defect survived five rounds of instrumentation.
layout(constant_id = 0) const uint pictureDebugMode = 0u;

const float k_pi = 3.1415927;

void main()
{
    if (pictureDebugMode == 1u)
    {
        out_color = vec4(1.0, 0.0, 1.0, 1.0);
        return;
    }
    vec3 nor = normalize(in_direction);
    if (pictureDebugMode >= 2u)
    {
        // 2 = the texture's RGB with alpha forced opaque. If the picture appears,
        // sampling works and only the alpha channel is wrong.
        // 3 = the sampled ALPHA as greyscale, opaque. White = alpha 1 (so the
        // fault is downstream), black = alpha 0 (the alpha is what kills it).
        vec2 duv = vec2(0.5 + 0.5 * atan(nor.x, -nor.z) / k_pi, acos(clamp(nor.y, -1.0, 1.0)) / k_pi);
        vec4 dtexel = texture(pictureTexture, duv);
        // 4 = layer.mOpacity as greyscale. Modes 2 and 3 proved the texture is
        // sound, so the only remaining factor in the alpha is the uniform. Black
        // here means mOpacity arrives as zero despite the CPU logging 1.000, and
        // that is a uniform plumbing bug, not a content one.
        if (pictureDebugMode == 4u) { out_color = vec4(vec3(layer.mOpacity), 1.0); return; }
        out_color = (pictureDebugMode == 2u) ? vec4(dtexel.rgb, 1.0) : vec4(vec3(dtexel.a), 1.0);
        return;
    }
    vec2 uv = vec2(0.5 + 0.5 * atan(nor.x, -nor.z) / k_pi, acos(clamp(nor.y, -1.0, 1.0)) / k_pi);
    vec4 texel = texture(pictureTexture, uv);
// Drawing::ColorSpace is { Linear = 0, Gamma = 1 } (drawing.h), and
// LayerRendererPicture::Init selects the fragment variant with
// fsIndex = static_cast<int>(colorSpace). These shaders had the test the wrong
// way round - they applied the gamma->linear conversion when colorSpace was
// LINEAR, which is our configuration. Every picture was therefore raised to the
// 2.2 power once too often: 360sky averages 29/255, and pow(0.113, 2.2) is
// 2/255, so it drew fully opaque and perfectly black against a black
// background. The brighter the source the less it showed - which is why the
// white 360 and the logo survived while every dark environment vanished.
#if COLOR_SPACE == 1
    vec3 color = pow(texel.rgb, vec3(2.2));
#else
    vec3 color = texel.rgb;
#endif
    float alpha = texel.a * layer.mOpacity;
    out_color = vec4(color, alpha);
}
'@

$vsPath = Join-Path $workDir "shader_pip360Equirect_vk.vert"
