$vs2DSource = @'
#version 460

// World-placed 2D picture quad, mirroring the GLES shader_pi2D_vs path:
// unit corners scaled by unSize (aspect, 1) in layer space, transformed by
// mLayerToViewer then the current eye's projection. The old version emitted
// raw NDC positions - every 2D picture rendered as a fullscreen head-locked
// overlay ("glued to my eyes").

layout (std140, row_major, binding=3) uniform LayersState
{
    mat4x4 mLayerToViewer;
    float  mLayerToViewerScale;
    float  mOpacity;
    float  mkUnused;
    float  mDrawInTime;
    vec4   mAnimParams;
    vec4   mKeepAlive[2];
    uint   mID;
} layer;

struct DisplayEye { mat4x4 mMatrix_CamPrj; };
layout (std140, row_major, binding=4) uniform DisplayState
{
    DisplayEye mEye[2];
    vec2       mResolution;
} display;

layout (std140, binding=5) uniform PassState
{
    int mID;
    int kk1;
    int kk2;
    int kk3;
} pass;

// Picture renderer constants: unSize.xy = (aspect ratio, 1).
layout (std140, binding=9) uniform PictureConstants
{
    vec4 unSize;
} constants;

layout(location=0) out vec2 out_uv;

void main()
{
    vec2 corners[6] = vec2[](
        vec2(-1.0, -1.0),
        vec2( 1.0, -1.0),
        vec2( 1.0,  1.0),
        vec2(-1.0, -1.0),
        vec2( 1.0,  1.0),
        vec2(-1.0,  1.0)
    );
    vec2 c = corners[gl_VertexIndex];
    vec3 opos = vec3(constants.unSize.xy * c, 0.0);
    vec3 viewer_position = (layer.mLayerToViewer * vec4(opos, 1.0)).xyz;
    out_uv = 0.5 + 0.5 * c * vec2(1.0, -1.0);
    gl_Position = display.mEye[pass.mID].mMatrix_CamPrj * vec4(viewer_position, 1.0);
}
'@

$fs2DSource = @'
#version 460

layout (std140, row_major, binding=3) uniform LayersState
{
    mat4x4 mLayerToViewer;
    float  mLayerToViewerScale;
    float  mOpacity;
    float  mkUnused;
    float  mDrawInTime;
    vec4   mAnimParams;
    vec4   mKeepAlive[2];
    uint   mID;
} layer;

layout(binding = 0) uniform sampler2D pictureTexture;
layout(location=0) in vec2 in_uv;
layout(location=0) out vec4 out_color;

// See the 360 shader: solid magenta when IMM_UNITY_VK_PIC_DEBUG is set. The 2D
// path is known to render (the Oculus logo), so this doubles as the control -
// if 2D goes magenta and 360 stays black, the debug path itself is proven live.
layout(constant_id = 0) const uint pictureDebugMode = 0u;

void main()
{
    if (pictureDebugMode == 1u)
    {
        out_color = vec4(1.0, 0.0, 1.0, 1.0);
        return;
    }
    if (pictureDebugMode >= 2u)
    {
        vec4 dtexel = texture(pictureTexture, in_uv);
        if (pictureDebugMode == 4u) { out_color = vec4(vec3(layer.mOpacity), 1.0); return; }
        out_color = (pictureDebugMode == 2u) ? vec4(dtexel.rgb, 1.0) : vec4(vec3(dtexel.a), 1.0);
        return;
    }
    vec4 texel = texture(pictureTexture, in_uv);
// Same inversion as the 360 shader: the squaring approximates gamma->linear and
// belongs on the Gamma branch, not the Linear one.
#if COLOR_SPACE == 1
    vec3 color = texel.rgb * texel.rgb;
#else
    vec3 color = texel.rgb;
#endif
    out_color = vec4(color, texel.a * layer.mOpacity);
}
'@

